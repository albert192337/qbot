// Production renderer/rules with isolated fixtures. No real save or external requests.
const {app,BrowserWindow,ipcMain,session}=require('electron');
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),ts=require(path.join(root,'node_modules/typescript'));
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022,esModuleInterop:true}}).outputText,f);
app.setPath('userData',fs.mkdtempSync(path.join(require('node:os').tmpdir(),'qbot-growth-')));
const wait=ms=>new Promise(r=>setTimeout(r,ms));
app.whenReady().then(async()=>{try{
 session.defaultSession.webRequest.onBeforeRequest({urls:['http://*/*','https://*/*']},(_,cb)=>cb({cancel:true}));
 const {initialGarden,transition}=require('../app/src/main/garden/rules.ts');
 const {gardenWeather}=require('../app/src/shared/garden-weather.ts');
 let n=0,now=Date.now();const rng={random:()=>.99,id:()=>`ui-growth-${n++}`};let state=initialGarden(now,rng);
 state.seeds[0].genes=['rainbow','nebula'];state=transition(state,{type:'plant',plot:0,seed:state.seeds[0].id},now,rng).state;
 state.seeds[0].genes=['golden'];state=transition(state,{type:'plant',plot:1,seed:state.seeds[0].id},now,rng).state;
 state=transition(state,{type:'mature'},now,rng).state;
 state.produce.push({...state.plots[1],id:'bag-gold'},{...state.plots[1],id:'bag-low',traits:[]});
 state.xp.lotus=440;
 const windows=[],errors=[];const broadcast=()=>windows.forEach(w=>w.webContents.send('garden:changed'));
 ipcMain.handle('settings:get',()=>({}));
 ipcMain.handle('garden:get',()=>state);ipcMain.handle('garden:weather',()=>gardenWeather(now));
 ipcMain.handle('garden:act',(_,cmd)=>{try{const r=transition(state,cmd,now,rng);state=r.state;broadcast();return {ok:true,...r};}catch(e){return {ok:false,error:e.message};}});
 ipcMain.on('garden:ignore',()=>{});ipcMain.on('garden:cancelPerformance',()=>{});
 const prefs={preload:path.join(root,'app/out/preload/index.js'),backgroundThrottling:false,offscreen:true};
 const panel=new BrowserWindow({width:860,height:760,show:false,webPreferences:prefs});
 const strip=new BrowserWindow({width:1100,height:800,show:false,webPreferences:prefs});windows.push(panel,strip);
 for(const w of windows)w.webContents.on('console-message',e=>{if(e.level==='error'){errors.push(e.message);console.error(e.message);}});
 await panel.loadFile(path.join(root,'app/out/renderer/garden/index.html'),{query:{view:'plot:0'}});
 await strip.loadFile(path.join(root,'app/out/renderer/garden/index.html'),{query:{view:'strip'}});
 strip.webContents.send('garden:anchor',{left:780,right:1040,top:350,bottom:700,side:'left'});
 const js=(w,code)=>w.webContents.executeJavaScript(code).catch(e=>{console.error('Failed renderer command:',code);throw e;});
 const until=async fn=>{for(let i=0;i<80;i++){if(await fn())return;await wait(75);}throw Error('UI timed out');};
 const click=async(w,text)=>{await js(w,`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(text)}&&!b.disabled);if(!b)throw Error('Missing button: '+${JSON.stringify(text)});b.click()})()`);await wait(150);};
 const out=path.join(root,'output/garden-growth-v2');fs.mkdirSync(out,{recursive:true});
 const shot=async(w,name)=>{await wait(200);fs.writeFileSync(path.join(out,name+'.png'),(await w.webContents.capturePage()).toPNG());};
 await until(()=>js(panel,'!!document.querySelector(".mystery-fruit")'));
 assert.ok(await js(panel,'!document.querySelector(".plant-detail").textContent.includes("星云")'),'All unrevealed traits stay hidden');
 assert.ok(await js(panel,'!document.querySelector(".plant-detail").textContent.includes("kg")'));
 await until(()=>js(strip,'!!document.querySelector("[data-plot] .art")'));
 await js(strip,'document.querySelector("[data-plot] .art").click()');await wait(150);
 assert.equal(state.produce.length,2,'clicking the crop must only open details');
 assert.ok(await js(strip,'!!document.querySelector(".quick-menu")'));
 await shot(panel,'rainbow-sealed');await shot(strip,'strip-details');
 await click(panel,'培育 · 约 3 分钟');assert.ok(state.plots[0].cultivation);
 now+=12000;await click(panel,'暂停培育');assert.equal(state.plots[0].cultivation.remainingMs,168000);
 await click(panel,'继续培育');now+=168000;
 state=transition(state,{type:'revealPlant',plot:0},now,rng).state;broadcast();
 await until(()=>js(panel,'!document.querySelector(".mystery-fruit")'));
 assert.ok(await js(panel,'document.querySelector(".plant-detail").textContent.includes("星云")'));
 assert.equal(state.produce.length,2);await shot(panel,'rainbow-revealed');
 await click(panel,'与背包果实繁育 ♡');
 assert.equal(await js(panel,'[...document.querySelectorAll("button")].filter(b=>b.textContent==="与它繁育").length'),1);
 await click(panel,'与它繁育');assert.equal(state.produce[0].bred,true);assert.equal(state.plots[0].bred,true);
 await click(panel,'植物图鉴');assert.ok(await js(panel,'document.body.textContent.includes("Lv.6")'));
 assert.equal(await js(panel,'document.querySelectorAll(".factor").length'),61);await shot(panel,'growth-book');
 await click(panel,'天气');await until(()=>js(panel,'document.querySelectorAll(".weather-catalog-row").length===6'));
 await shot(panel,'weather-catalog');panel.setSize(420,620);await wait(150);
 assert.ok(await js(panel,'document.documentElement.scrollWidth<=innerWidth'));await shot(panel,'weather-small');
 assert.deepEqual(errors,[]);console.log('PASS: known traits before reveal, pause/resume/reveal, breeding, 60 factor definitions, six weathers and narrow layout. '+out);app.exit(0);
}catch(e){console.error(e);app.exit(1);}});
