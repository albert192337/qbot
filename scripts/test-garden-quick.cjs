// Native desktop quick menus. Production renderer/preload/service; isolated save, no network.
const { app, BrowserWindow, ipcMain, session } = require('electron');
const fs = require('node:fs'), fsp = require('node:fs/promises'), path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const ts = require(path.join(root, 'node_modules/typescript'));
require.extensions['.ts'] = (m, f) => m._compile(ts.transpileModule(fs.readFileSync(f, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText, f);
const data = fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'qbot-quick-'));
app.setPath('userData', data);
const wait = ms => new Promise(r => setTimeout(r, ms));
app.whenReady().then(async () => {
  try {
    session.defaultSession.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (_r, cb) => cb({ cancel: true }));
    const { initialGarden, transition } = require('../app/src/main/garden/rules.ts');
    let id = 0; const rng = { random: () => .8, id: () => `quick-${id++}` };
    let s = initialGarden(Date.now(), rng);
    s = transition(s, { type: 'plant', plot: 1, seed: s.seeds.find(x => x.species === 'strawberry').id }, Date.now(), rng).state;
    s = transition(s, { type: 'mature' }, Date.now(), rng).state;
    s = transition(s, { type: 'harvest', plot: 1 }, Date.now(), rng).state;
    s = transition(s, { type: 'plant', plot: 2, seed: s.seeds.find(x => x.species === 'sunflower').id }, Date.now(), rng).state;
    s.plots[2].traits = ['giant', 'punk', 'classical', 'mint']; s.plots[2].readyAt = Date.now() - 1;
    await fsp.writeFile(path.join(data, 'garden-demo.json'), JSON.stringify({ state: s }));
    const { getGarden, gardenAction } = require('../app/src/main/garden/service.ts');
    let opened = 0, ignored = true;
    ipcMain.handle('garden:get', () => getGarden()); ipcMain.handle('garden:act', (_e, cmd) => gardenAction(cmd));
    ipcMain.on('garden:open', () => opened++); ipcMain.on('garden:ignore', (_e, next) => { ignored = next; });
    const win = new BrowserWindow({ width: 1100, height: 800, transparent: true, frame: false, show: false, webPreferences: { preload: path.join(root, 'app/out/preload/index.js'), contextIsolation: true, backgroundThrottling: false } });
    const js = code => win.webContents.executeJavaScript(code);
    const until = async cb => { for (let i = 0; i < 80; i++) { if (await cb()) return; await wait(100); } throw Error('quick UI timeout'); };
    const click = async selector => {
      const p = await js(`(()=>{const el=${selector};if(!el)throw Error('missing element');el.scrollIntoView({block:'nearest'});const r=el.getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()`);
      win.webContents.sendInputEvent({ type: 'mouseMove', ...p });
      win.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...p });
      win.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...p }); await wait(250);
    };
    const btn = text => `[...document.querySelectorAll('.quick-menu button,dialog button')].find(b=>b.textContent.includes(${JSON.stringify(text)})&&!b.disabled)`;
    const output = path.join(root, '.superpowers/garden-preview'); await fsp.mkdir(output, { recursive: true });
    const shot = async name => { await js(`Promise.all([...document.images].map(i=>i.decode().catch(()=>{})))`); await wait(200); await fsp.writeFile(path.join(output, name+'.png'), (await win.webContents.capturePage()).toPNG()); };
    await win.loadFile(path.join(root, 'app/out/renderer/garden/index.html'), { query: { view: 'strip' } }); win.show();
    win.webContents.send('garden:anchor', { left: 730, right: 1090, top: 400, bottom: 735, side:'left' });
    const assertClear = async () => {
      const bottom = await js(`document.querySelector('.quick-menu').getBoundingClientRect().bottom`);
      const plantTop = await js(`Math.min(400,...[...document.querySelectorAll('.plot .art')].map(p=>p.getBoundingClientRect().top))`);
      assert.ok(bottom <= plantTop - 15, `menu bottom ${bottom} must stay above pet/plants ${plantTop}`);
    };
    await until(() => js(`document.querySelectorAll('.plot').length===6`));
    const assertToolsClear = async () => assert.ok(await js(`(()=>{const t=document.querySelector('.garden-tools').getBoundingClientRect();return [...document.querySelectorAll('.plot .art')].every(p=>{const r=p.getBoundingClientRect();return r.right<t.left||r.left>t.right})})()`), '工具栏不得覆盖巨型植物');
    await assertToolsClear();
    assert.equal(await js(`document.querySelectorAll('[data-plot="2"] .spark').length`),0);
    assert.equal(await js(`document.querySelectorAll('[data-plot="2"] .fx-punk span').length`),4);
    assert.equal(await js(`document.querySelectorAll('[data-plot="2"] .fx-classical span').length`),4);
    assert.notEqual(await js(`getComputedStyle(document.querySelector('[data-plot="2"] .fx-punk span')).animationName`), 'none');
    await click(`document.querySelector('[data-plot="0"] .soil')`);
    assert.ok(await js(`document.querySelector('.quick-menu').textContent.includes('莲花 ×2')`));
    const bounds = await js(`(()=>{const r=document.querySelector('.quick-menu').getBoundingClientRect();return [r.width,r.height,r.x,r.y]})()`);
    assert.ok(bounds[0]<=280 && bounds[1]<=350 && bounds[2]>=0 && bounds[3]>=0);
    await shot('quick-seeds');
    win.webContents.send('garden:speechBounds',{left:300,right:640,top:260,bottom:395});await wait(100);
    assert.ok(await js(`document.querySelector('.quick-menu').getBoundingClientRect().bottom<=244`),'花园菜单避开台词气泡');
    win.webContents.send('garden:speechBounds',null);await wait(100);
    await click(btn('莲花 ×2')); await until(async () => !!(await getGarden()).plots[0]);
    assert.equal(await js(`document.querySelectorAll('.quick-menu').length`), 1, 'plant transition must not duplicate menu');
    assert.ok(await js(`document.querySelector('.quick-menu').textContent.includes('加速 ×2')`));
    await click(btn('加速 ×2'));
    assert.equal((await getGarden()).fertilizers.speed, 1);
    assert.ok(await js(`document.querySelector('.quick-menu').textContent.includes('加速 ×1')`));
    await shot('quick-fertilizers');
    await assertClear();
    await click(btn('测试：立即成熟')); await until(() => js(`!![...document.querySelectorAll('.quick-menu button')].find(b=>b.textContent==='收获 ✦')`));
    assert.equal(await js(`document.querySelectorAll('.quick-menu').length`), 1, 'maturity transition must not duplicate menu');
    assert.equal(await js(`document.querySelectorAll('.plot-label').length`), 0);
    assert.equal(await js(`[...document.querySelectorAll('.garden-tools button')].every(b=>!b.textContent.trim()&&b.querySelector('svg')&&b.getAttribute('aria-label'))`), true);
    // Close the menu and click the flower itself, not a large management view.
    await click(btn('×'));
    await click(`document.querySelector('[data-plot="0"] .art')`);
    await until(() => js(`!!document.querySelector('.result-card')`));
    assert.equal(await js(`document.querySelectorAll('dialog').length`), 0, 'harvest is non-modal');
    assert.ok(await js(`document.querySelector('.result-card').textContent.includes('kg')&&!!document.querySelector('.result-card img')`));
    const resultBounds = await js(`(()=>{const r=document.querySelector('.result-card').getBoundingClientRect();return [r.width,r.height]})()`);
    assert.ok(resultBounds[0]<=280 && resultBounds[1]<=350);
    assert.ok(await js(`(()=>{const e=document.querySelector('.result-card .quick-list');return e.scrollHeight<=e.clientHeight+1&&getComputedStyle(e).overflowY==='visible'})()`),'harvest result has no scrolling area');
    await shot('quick-harvest');
    await assertClear();
    await click(btn('收好'));
    await until(() => js(`!document.querySelector('.result-card')`));
    assert.equal(await js(`document.querySelectorAll('.quick-menu').length`), 0, '收好后不自动打开土地菜单');
    await click(`document.querySelector('[data-plot="0"] .soil')`);
    assert.equal(await js(`document.querySelector('.quick-menu').textContent.includes('已收进背包')`), false);
    await click(btn('繁育 ♡'));
    await shot('quick-parents');
    await click(btn('草莓 · 背包'));
    await until(() => js(`document.querySelector('.quick-menu').textContent.includes('繁育种子 ×1')`));
    assert.equal(await js(`document.querySelectorAll('.quick-menu').length`), 1, 'breeding transition must not duplicate menu');
    assert.ok(await js(`!!document.querySelector('.result-card img')&&document.querySelector('.result-card').textContent.includes('重量待成熟')`));
    assert.equal(await js(`document.querySelectorAll('dialog[open]').length`), 0, 'breeding stays compact');
    await shot('quick-bred');
    assert.equal(opened, 0, 'routine tasks never open management window');
    assert.equal(BrowserWindow.getAllWindows().length, 1);
    win.webContents.sendInputEvent({ type: 'keyDown', keyCode: 'ESC' }); win.webContents.sendInputEvent({ type: 'keyUp', keyCode: 'ESC' });
    await until(() => js(`!document.querySelector('.quick-menu')`));
    win.webContents.send('garden:anchor', { left:10,right:370,top:400,bottom:735,side:'right' });
    await wait(200);
    assert.ok(await js(`[...document.querySelectorAll('.plot')].every(p=>p.getBoundingClientRect().left>370)`));
    await assertToolsClear();
    await shot('garden-right-side');
    win.webContents.sendInputEvent({ type: 'mouseMove', x: 550, y: 250 }); await wait(100); assert.equal(ignored, true, 'blank space stays click-through');
    console.log('PASS: direct desktop planting/fertilizing/flower harvest/breeding, grouped counts, compact bounds, reveal mouse routing, escape and blank click-through; no management window opened.'); app.exit(0);
  } catch (e) { console.error(e); app.exit(1); }
});
