    await page.screenshot({path:path.join(output,'configure.png')});
    await page.locator('[data-generate]').click();await page.getByRole('dialog').waitFor();
    await page.getByRole('button',{name:'取消',exact:true}).click();
    assert.equal(await app.evaluate(()=>global.qa.calls.filter(c=>c[0]==='sticker-generate').length),0);
    await page.locator('[data-method]').selectOption('frame');
    await page.locator('[data-seconds]').fill('0.5');
    await page.locator('[data-description]').fill('开心地轻轻摇摆，首尾一致');
