    await page.locator('[data-search]').fill('开心');await page.locator('[data-search]').press('Tab');
    assert.equal(await page.locator('.sw-card').count(),1);
    await page.locator('[data-next-stage]').click();
    await page.locator('[data-scene=idle]').selectOption('st_0');
    await page.locator('[data-scene=drag]').selectOption('st_1');
    await page.locator('[data-create]').click();
    await page.locator('[data-save]').waitFor();
    const req=await app.evaluate(()=>global.qa.calls.find(c=>c[0]==='sticker-create')[1]);
    assert.equal(req.items.length,255);assert.equal(req.name,'小白狗测试');
