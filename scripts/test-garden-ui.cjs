// Real Electron/preload/renderer + production garden service. Isolated save; HTTP blocked.
const { app, BrowserWindow, ipcMain, session } = require('electron');
const fs = require('node:fs');
const fsp = require('node:fs/promises');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const ts = require(path.join(root, 'node_modules/typescript'));
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true } }).outputText, filename);
const wait = ms => new Promise(r => setTimeout(r, ms));
const output = path.join(root, '.superpowers/garden-preview');
const data = fs.mkdtempSync(path.join(require('node:os').tmpdir(), 'qbot-garden-'));
app.setPath('userData', data);
app.whenReady().then(async () => {
  try {
    await fsp.mkdir(output, { recursive: true });
    session.defaultSession.webRequest.onBeforeRequest({ urls: ['http://*/*', 'https://*/*'] }, (_r, cb) => cb({ cancel: true }));
    const { initialGarden } = require('../app/src/main/garden/rules.ts');
    let id = 0; const state = initialGarden(Date.now(), { random: () => .8, id: () => `qa-${id++}` });
    state.seeds[0].genes = ['giant', 'shiny', 'twin', 'purple']; state.seeds[0].bred = true;
    await fsp.writeFile(path.join(data, 'garden-demo.json'), JSON.stringify({ state }));
    const { getGarden, gardenAction } = require('../app/src/main/garden/service.ts');
    const { getProgress, openBox, flushProgress } = require('../app/src/main/progress.ts');
    ipcMain.handle('garden:get', () => getGarden());
    ipcMain.handle('garden:act', (_ev, cmd) => gardenAction(cmd));
    ipcMain.on('garden:ignore', () => {});
    const webPreferences = { preload: path.join(root, 'app/out/preload/index.js'), backgroundThrottling: false, contextIsolation: true };
    const panel = new BrowserWindow({ width: 860, height: 740, show: false, webPreferences });
    const strip = new BrowserWindow({ width: 1100, height: 580, transparent: true, frame: false, show: false, webPreferences });
    const errors = [];
    for (const win of [panel, strip]) win.webContents.on('console-message', (event) => { if (event.level === 'error') { errors.push(event.message); console.error('renderer:', event.message); } });
    await panel.loadFile(path.join(root, 'app/out/renderer/garden/index.html'), { query: { view: 'plot:0' } });
    await strip.loadFile(path.join(root, 'app/out/renderer/garden/index.html'), { query: { view: 'strip' } });
    strip.webContents.send('garden:anchor', { left: 370, right: 730, bottom: 530 });
    const js = code => panel.webContents.executeJavaScript(code).catch(e => { console.error('Failed JS:', code); throw e; });
    const until = async condition => { for (let i = 0; i < 80; i++) { if (await condition()) return; await wait(100); } throw Error('UI condition timed out'); };
    const click = async label => {
      const pos = await js(`(()=>{const e=[...document.querySelectorAll('button')].find(e=>e.textContent.trim()===${JSON.stringify(label)}&&!e.disabled);if(!e)throw Error('missing button '+${JSON.stringify(label)});e.scrollIntoView({block:'center'});const r=e.getBoundingClientRect();return {x:Math.round(r.x+r.width/2),y:Math.round(r.y+r.height/2)}})()`);
      panel.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...pos }); panel.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...pos }); await wait(250);
    };
    const shot = async (win, name) => { win.showInactive(); await win.webContents.executeJavaScript(`Promise.all([...document.images].map(img=>img.decode().catch(()=>{})))`); await wait(500); await fsp.writeFile(path.join(output, name + '.png'), (await win.webContents.capturePage()).toPNG()); };
    await until(() => js(`document.querySelectorAll('.seed-card').length===4`));
    panel.showInactive();
    await click('种在这里');
    await until(async () => !!(await getGarden()).plots[0]);
    await shot(strip, 'seedling');
    await click('2号 空地');
    // Choose strawberry through the actual rendered seed card.
    await js(`(()=>{const card=[...document.querySelectorAll('.seed-card')].find(c=>c.textContent.includes('草莓'));card.querySelector('button').click()})()`);
    await until(async () => !!(await getGarden()).plots[1]);
    await click('测试：立即成熟');
    await until(() => js(`!![...document.querySelectorAll('button')].find(b=>b.textContent==='收获 ✦')`));
    await shot(strip, 'mature-giant');
    await click('收获 ✦');
    await until(() => js(`!!document.querySelector('.result-card')`));
    assert.equal((await getGarden()).produce.length, 1);
    await shot(panel, 'harvest');
    await click('收好');
    await click('1号 莲花'); await click('繁育 ♡');
    await until(() => js(`document.querySelectorAll('.parent-row').length===1`));
    await click('与它繁育'); await until(() => js(`!!document.querySelector('.result-card')`));
    const after = await getGarden(); assert.equal(after.plots[0].bred, true); assert.equal(after.produce[0].bred, true);
    assert.ok(after.seeds.at(-1).parents.includes('lotus') && after.seeds.at(-1).parents.includes('strawberry'));
    await shot(panel, 'breeding'); await click('收好');
    await click('收获 ✦'); await until(() => js(`!!document.querySelector('.result-card')`)); await click('收好');
    await click('植物图鉴'); await until(() => js(`document.querySelectorAll('.factor.unlocked').length===5`));
    await shot(panel, 'book');
    const beforePoints = (await getProgress()).points;
    const discoveries = await getGarden();
    const award = discoveries.discovered.filter(k => !discoveries.claimed.includes(k)).length * 20;
    await click(`一键领取本次积分 · ${award}`); await until(() => js(`!!document.querySelector('.result-card')`));
    assert.equal((await getProgress()).points, beforePoints + award);
    await click('收好');
    await click('背包'); await shot(panel, 'bag');
    await click('限时商店'); await shot(panel, 'shop');
    const offer = (await getGarden()).shop.offers[0]; await click(`◉ ${offer.price} · 买一份`);
    assert.equal((await getGarden()).shop.offers[0].stock, offer.stock - 1);
    const preBox = await getGarden(); const reward = await openBox(); assert.equal(reward.ok, true); assert.ok(reward.gardenReward);
    assert.equal((await getGarden()).seeds.length, preBox.seeds.length + 1);
    const images = await js(`Promise.all([...document.images].map(img=>img.decode().then(()=>true,()=>false)))`); assert.ok(images.every(Boolean));
    await panel.setSize(560, 580); await shot(panel, 'small-window');
    assert.ok(await js(`document.documentElement.scrollWidth<=window.innerWidth`), 'no horizontal overflow');
    await panel.reload(); await wait(700); assert.equal((await getGarden()).seeds.length, preBox.seeds.length + 1);
    await flushProgress();
    assert.deepEqual(JSON.parse(await fsp.readFile(path.join(data, 'garden-demo.json'), 'utf8')).state, await getGarden());
    assert.deepEqual(errors, []);
    console.log('PASS: real UI planting, maturity, harvest reveal, cross-species land/bag breeding, encyclopedia points, shop, box supplies, persistence, images, narrow window.');
    console.log('Screenshots:', output); app.exit(0);
  } catch (e) { console.error(e); app.exit(1); }
});
