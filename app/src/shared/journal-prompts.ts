export type JournalPromptKey = keyof typeof JOURNAL_PROMPTS;
export function journalPrompt(key: JournalPromptKey, override?: string): string {
  return typeof override === 'string' && override.trim() ? override.trim().slice(0, 12000) : JOURNAL_PROMPTS[key].text;
}
